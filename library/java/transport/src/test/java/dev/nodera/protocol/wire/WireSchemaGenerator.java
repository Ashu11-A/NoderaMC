package dev.nodera.protocol.wire;

import dev.nodera.testkit.harness.LayoutManifest;
import java.util.stream.Collectors;

/**
 * Renders the artefacts that are <b>derived</b> from {@link WireRegistry} rather than maintained
 * beside it (Task 14 phase 1, {@code Plan.7} decision D6 — the schema is the source).
 *
 * <p>Two things came out of hand-maintained duplication and are now generated from the one table:
 *
 * <ul>
 *   <li>{@code rust/nodera-codec/src/kinds.rs} — the Rust kind registry. It used to be a
 *       hand-copied subset, which is why it could hold 24 of the 72 kinds and still look complete:
 *       nothing said what was missing.</li>
 *   <li>{@code fixtures/wire/manifest.json} — which kind each golden fixture pins, and which plane
 *       governs its bytes. A fixture with no kind, or a kind with no fixture, is visible in a text
 *       diff instead of being invisible in a directory listing.</li>
 * </ul>
 *
 * <p>The renderers are pure functions of the registry; {@code WireSchemaGeneratorTest} compares
 * their output with what is checked in and fails on a difference, so the generated files cannot go
 * stale without CI saying so.
 *
 * <p>Thread-context: stateless; any thread.
 */
final class WireSchemaGenerator {

    /**
     * Path of the generated Rust registry, relative to the repository root.
     *
     * <p>Composed from {@code layout.properties} rather than spelled out: this was a literal
     * {@code "rust/nodera-codec/src/kinds.rs"} and it went stale the moment the crate moved, which
     * failed the generator check with a missing file rather than with a schema drift.
     */
    static final String RUST_KINDS_PATH =
            LayoutManifest.load().value("crate.nodera-codec") + "/src/kinds.rs";

    /** Path of the generated fixture manifest, relative to the repository root. */
    static final String FIXTURE_MANIFEST_PATH = "fixtures/wire/manifest.json";

    private static final String BANNER = """
            // @generated by the transport module's WireSchemaGenerator from
            // its own dev/nodera/protocol/wire/WireRegistry.java.
            //
            // DO NOT EDIT BY HAND. Add the kind to WireRegistry and re-run:
            //     ./gradlew :transport:test --tests '*WireSchemaGeneratorTest' \\
            //         -Dnodera.wire.regenerate=true
            """;

    private WireSchemaGenerator() {}

    /**
     * Render the Rust kind registry.
     *
     * @return the complete contents of {@link #RUST_KINDS_PATH}, newline-terminated.
     * @Thread-context any thread.
     */
    static String renderRustKinds() {
        StringBuilder out = new StringBuilder(8192);
        out.append(BANNER);
        out.append("""

                //! The wire schema, mirrored from Java.
                //!
                //! Both implementations read the same numbers because both are produced from the same
                //! table. `tests/tag_mirror.rs` re-parses the Java source and fails if this file has
                //! drifted from it, so a kind cannot exist on one side alone.

                /// The wire epoch this build speaks; it appears in every frame header.
                pub const WIRE_EPOCH: u16 =""")
                // A text block drops the trailing space after "=", so it is written explicitly.
                .append(' ').append(WireRegistry.WIRE_EPOCH).append(";\n");

        out.append("""

                /// Message frame kinds. Assigning a number is permanent: never renumber, never reuse.
                pub mod message_tags {
                """);
        for (WireKind k : WireRegistry.kinds()) {
            out.append("    /// `").append(k.name()).append("` — ")
                    .append(k.plane() == MessagePlane.CONSENSUS ? "consensus" : "infrastructure")
                    .append(" plane.\n");
            out.append("    pub const ").append(k.rustConstantName()).append(": u16 = ")
                    .append(k.kind()).append(";\n");
        }
        out.append("\n    /// Highest kind assigned on the Java side; new kinds start at `NEXT_TAG + 1`.\n");
        out.append("    pub const NEXT_TAG: u16 = ").append(WireRegistry.NEXT_KIND).append(";\n}\n");

        out.append("""

                /// Which encoding contract governs a kind's body.
                ///
                /// `Consensus` bodies are hashed and signed, so they are strict and byte-exact;
                /// `Infrastructure` bodies are TLV, so a field a peer does not know is skipped
                /// instead of destroying the rest of the message.
                #[derive(Debug, Clone, Copy, PartialEq, Eq)]
                pub enum Plane {
                    /// Hashed / signed. Strict positional encoding, carried as opaque bytes.
                    Consensus,
                    /// Reachability and discovery. Forward-compatible TLV.
                    Infrastructure,
                }

                /// One row of the wire schema.
                #[derive(Debug, Clone, Copy)]
                pub struct KindRow {
                    /// The permanent wire number.
                    pub kind: u16,
                    /// The stable display name — the Java record's simple name.
                    pub name: &'static str,
                    /// Which encoding contract governs the body.
                    pub plane: Plane,
                }

                /// Every kind, ascending.
                pub const KINDS: &[KindRow] = &[
                """);
        for (WireKind k : WireRegistry.kinds()) {
            // Emitted in the shape `cargo fmt` produces. A generated file still has to pass the
            // same format gate as a hand-written one, and a renderer that fights rustfmt turns
            // every regeneration into a red build.
            out.append("    KindRow {\n")
                    .append("        kind: ").append(k.kind()).append(",\n")
                    .append("        name: \"").append(k.name()).append("\",\n")
                    .append("        plane: Plane::")
                    .append(k.plane() == MessagePlane.CONSENSUS ? "Consensus" : "Infrastructure")
                    .append(",\n    },\n");
        }
        out.append("];\n");

        out.append("""

                /// The row for a kind, or `None` when this build does not know it.
                ///
                /// An unknown kind is a routine event, not an error: a newer peer may send one, and
                /// the frame is skipped and answered rather than killing the connection.
                pub fn find(kind: u16) -> Option<&'static KindRow> {
                    KINDS.iter().find(|row| row.kind == kind)
                }

                /// The stable display name of a kind.
                pub fn name_of(kind: u16) -> Option<&'static str> {
                    find(kind).map(|row| row.name)
                }

                /// Which plane governs a kind's body.
                pub fn plane_of(kind: u16) -> Option<Plane> {
                    find(kind).map(|row| row.plane)
                }

                #[cfg(test)]
                mod tests {
                    use super::*;

                    #[test]
                    fn kinds_are_unique_and_contiguous() {
                        for (index, row) in KINDS.iter().enumerate() {
                            assert_eq!(
                                row.kind as usize,
                                index + 1,
                                "the kind table must be ascending and contiguous"
                            );
                        }
                        assert_eq!(KINDS.len(), message_tags::NEXT_TAG as usize);
                    }

                    #[test]
                    fn every_kind_resolves_to_itself() {
                        for row in KINDS {
                            assert_eq!(find(row.kind).map(|r| r.name), Some(row.name));
                            assert_eq!(plane_of(row.kind), Some(row.plane));
                        }
                        assert!(find(message_tags::NEXT_TAG + 1).is_none());
                    }
                }
                """);
        return out.toString();
    }

    /**
     * Render the fixture manifest: one JSON object per kind, in kind order.
     *
     * @return the complete contents of {@link #FIXTURE_MANIFEST_PATH}, newline-terminated.
     * @Thread-context any thread.
     */
    static String renderFixtureManifest() {
        String rows = WireRegistry.kinds().stream()
                .map(k -> "    { \"kind\": %d, \"name\": \"%s\", \"plane\": \"%s\", \"fixture\": \"%s\" }"
                        .formatted(k.kind(), k.name(),
                                k.plane() == MessagePlane.CONSENSUS ? "consensus" : "infrastructure",
                                k.fixtureName()))
                .collect(Collectors.joining(",\n"));
        return """
                {
                  "_generated": "by java/transport's WireSchemaGenerator from WireRegistry.java; do not edit",
                  "wireEpoch": %d,
                  "kinds": [
                %s
                  ]
                }
                """.formatted(WireRegistry.WIRE_EPOCH, rows);
    }
}
